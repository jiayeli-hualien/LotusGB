#!/usr/bin/env python3
"""Generate typed C++ opcode tables from the checked-in CSV sources."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = ROOT / "src/lib/include"
OUTPUT = INCLUDE / "generated_decode_tables.hpp"
TABLES = [
    ("decodeRules", "decode_table.csv", "decode"),
    ("instructions", "instruction_table.csv", "instructions"),
    ("cbDecodeRules", "cb_decode_table.csv", "decode"),
    ("cbInstructions", "cb_instruction_table.csv", "instructions"),
]


def read_rows(path):
    with path.open(newline="") as source:
        rows = list(csv.reader(source, skipinitialspace=True))
    return rows[1:]


def main():
    tables = {name: (kind, read_rows(INCLUDE / filename))
              for name, filename, kind in TABLES}
    instruction_ids = {}
    enum_items = []
    for table_name, (kind, rows) in tables.items():
        if kind != "instructions":
            continue
        prefix = "Base" if table_name == "instructions" else "CB"
        for index, row in enumerate(rows):
            if index > 255:
                raise ValueError(f"too many instructions in {table_name}")
            enum_name = f"{prefix}_{row[0]}"
            instruction_ids[(table_name, row[0])] = enum_name
            enum_items.append(f"    {enum_name} = {index},")
    lines = [
        "// Generated by tools/generate_decode_tables.py; do not edit.",
        "#ifndef LOTUSGB_GENERATED_DECODE_TABLES_HPP",
        "#define LOTUSGB_GENERATED_DECODE_TABLES_HPP",
        "#include <array>", "#include <cstdint>", "#include <string_view>", "#include <vector>",
        '#include "instSubFunc.hpp"', '#include "instSubFuncCB.hpp"',
        '#include "instSubFuncCommon.hpp"',
        "namespace LOTUSGB::GeneratedDecodeTables {",
        "enum class InstructionId : uint8_t {",
        *enum_items,
        "};",
        "struct DecodeRule { InstructionId instruction; uint8_t mask; uint8_t value; };",
        "struct InstructionRow { InstructionId id; std::string_view name; std::vector<IInstruction::FUNC_TYPE> functions; };",
    ]
    instruction_tables = {
        "decodeRules": "instructions",
        "cbDecodeRules": "cbInstructions",
    }
    for name, (kind, rows) in tables.items():
        if kind == "decode":
            instruction_rows = tables[instruction_tables[name]][1]
            instruction_table_name = instruction_tables[name]
            instruction_indices = {row[0] for row in instruction_rows}
            lines.append(f"inline constexpr DecodeRule {name}[] = {{")
            for row in rows:
                if row[0] not in instruction_indices:
                    raise ValueError(f"unknown instruction in {name}: {row[0]}")
                lines.append(
                    f'    {{InstructionId::{instruction_ids[(instruction_table_name, row[0])]}, '
                    f'0x{int(row[1], 16):02X}, '
                    f'0x{int(row[2], 16):02X}}},'
                )
        else:
            lines.append(f"inline const InstructionRow {name}[] = {{")
            for row in rows:
                functions = [part.strip() for part in row[2:]]
                cycles = int(row[1])
                if len(functions) != cycles:
                    raise ValueError(f"cycle count mismatch in {name}: {row[0]}")
                encoded = ", ".join(f"subFunc{item}" for item in functions)
                lines.append(
                    f'    {{InstructionId::{instruction_ids[(name, row[0])]}, '
                    f'"{row[0]}", {{{encoded}}}}},'
                )
        lines.append("};")
    lines += ["}", "#endif", ""]
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
